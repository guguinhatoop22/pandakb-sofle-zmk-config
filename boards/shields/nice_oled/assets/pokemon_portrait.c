/*
 * =============================================================================
 * PRE-ROTATED POKÉMON SPRITES (32x32) FOR SOFLE HYBRID LEFT OLED
 * =============================================================================
 *
 * SSD1306 Physical Panel: 128x32 (landscape, visible horizontally).
 *
 * Canvas Pipeline:
 *   1. Screen is drawn on a portrait canvas buffer (CANVAS_BUF: 160x160).
 *   2. The function rotate_canvas() in util.c applies:
 *          lv_canvas_transform(canvas, &img, 900, ...)
 *      which rotates the canvas bitmap 90 degrees CLOCKWISE around pivot (80, 80).
 *   3. Under 90-deg CW rotation:
 *          X_screen = 160 - Y_canvas
 *          Y_screen = X_canvas
 *
 * Orientation Mapping:
 *   - On the physical keyboard, 'virado para o meu lado' (facing the user/typist)
 *     means:
 *          Feet / bottom of sprite = Y_screen = 31 (bottom edge, towards typist)
 *          Head / top of sprite   = Y_screen = 0  (top edge, away from typist)
 *
 *   - The original pokemon.c sprites are oriented in standard landscape:
 *          L[row, col] has Head at small row, Feet at large row.
 *
 *   - To make the sprite appear right-side-up on the physical OLED:
 *          P[r, c] = L[c, 31 - r]
 *     (which rotates the landscape bitmap 90 degrees COUNTER-CLOCKWISE / 270 deg CW).
 *     When rotate_canvas() applies its 90-deg CW rotation, (+90 - 90 = 0),
 *     the sprite displays completely UPRIGHT and facing the user.
 *
 * NOTE: P[r, c] = L[31 - c, r] was 90-deg in the opposite direction, causing
 *       the sprite to display upside down. P[r, c] = L[c, 31 - r] is the
 *       EXACT and CORRECT orientation! NÃO ESQUECER JAMAIS!
 * =============================================================================
 */
